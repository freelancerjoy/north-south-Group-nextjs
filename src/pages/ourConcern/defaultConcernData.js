export const hasDefaultConcern = (slug) =>
  Object.prototype.hasOwnProperty.call(defaults, slug);

export const getDefaultConcern = (slug) => {
  if (!hasDefaultConcern(slug)) return null;

  const concern = { ...common, ...defaults[slug] };
  const derivedImages = uniqueImages([
    concern.heroImage,
    concern.aboutImage,
    ...(concern.services || []).map((item) => item.image),
  ]);

  return {
    ...concern,
    heroSliderImages:
      concern.heroSliderImages?.length > 0
        ? uniqueImages(concern.heroSliderImages).slice(0, 3)
        : derivedImages.slice(0, 3),
    galleryImages:
      concern.galleryImages?.length > 0
        ? uniqueImages(concern.galleryImages)
        : [...derivedImages, ...derivedImages.slice(0, 2)],
    features:
      concern.features?.length > 0
        ? concern.features
        : (concern.services || []).slice(0, 3).map((item) => ({
            title: item.title,
            text: item.text,
            image: item.image,
          })),
  };
};
